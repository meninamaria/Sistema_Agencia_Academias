    private void botao_confirmaAvaliarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botao_confirmaAvaliarActionPerformed
        if (academia == null) {
        JOptionPane.showMessageDialog(
            this,
            "Nenhuma academia selecionada para avaliação.",
            "Erro",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    String texto = campoNota.getText();

    if (texto.trim().isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Campo vazio. Informe uma nota!",
            "Erro",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    double nota;

    try {
        nota = Double.parseDouble(texto);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Número inválido!");
        return;
    }

    if (nota < 0.0 || nota > 5.0) {
        JOptionPane.showMessageDialog(this, "Nota deve estar entre 0.0 e 5.0!");
        return;
    }

    boolean sucesso = gerenciamento.avaliarAcademia(academia, nota);

    if (sucesso) {
        JOptionPane.showMessageDialog(
            this,
            "Academia avaliada com sucesso!",
            "Avaliação",
            JOptionPane.INFORMATION_MESSAGE
        );

        campoNota.setText("");
        campoID_avaliarAcad.setText("");
        campoNota.setEnabled(false);
        botao_confirmaAvaliar.setEnabled(false);
        academia = null;
        new TelaMenuUsuario(clienteLogado).setVisible(true);
        this.dispose();

    } else {
        JOptionPane.showMessageDialog(
            this,
            "Erro ao avaliar academia!",
            "Erro",
            JOptionPane.ERROR_MESSAGE
        );
    }


           
    }//GEN-LAST:event_botao_confirmaAvaliarActionPerformed

