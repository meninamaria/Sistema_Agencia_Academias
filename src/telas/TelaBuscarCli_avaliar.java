    private void botao_OKActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botao_OKActionPerformed
        String busca = campoID_avaliarAcad.getText();
        
        if (busca.trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Campo vazio. Informe o nome da academia  que deseja avaliar!", "[ERROR] Cadastro", JOptionPane.ERROR_MESSAGE);
        } else {
            academia = gerenciamento.buscarAcademia(busca);
            if (academia != null) {
                botao_confirmaAvaliar.setEnabled(true);
                campoNota.setEnabled(true);
            } else {
                JOptionPane.showMessageDialog(null, "Nenhuma academia encontrada!\n", "Buscar Academia", JOptionPane.ERROR_MESSAGE);
            }
        }

        
    }//GEN-LAST:event_botao_OKActionPerformed

