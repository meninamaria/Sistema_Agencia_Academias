    private void botao_atualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botao_atualizarActionPerformed
        String nome = campoNome_atua.getText();
        String endereco = campoEndereco_atua.getText();
        String telefone = campoTelefone_atua.getText();
        String texto = campoMensalidade_atua.getText();
        String atividadesOfertadas = campoAtividadesOfert_atua.getText();
        String texto2 = campoPersonais_atua.getText();

        Double mensalidade;
        int qtd_personais;

        try {
            mensalidade = Double.parseDouble(texto);
            qtd_personais = Integer.parseInt(texto2);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Por favor, informe um valor válido", "[ERROR] Atualizar", JOptionPane.ERROR_MESSAGE);
            return;
        }
                
        if ((nome.trim().isEmpty()) || (endereco.trim().isEmpty()) || (telefone.trim().isEmpty()) || (texto.trim().isEmpty()) || (texto2.trim().isEmpty()) || (atividadesOfertadas.trim().isEmpty())) {
            JOptionPane.showMessageDialog(null, "Campo Vazio. Por favor, preencha todos os campos!", "[ERROR] Atualizar", JOptionPane.ERROR_MESSAGE);
        } else {
            
            if (qtd_personais < 0) {
                JOptionPane.showMessageDialog(this, "Por favor, informe um valor válido", "[ERROR] Atualizar", JOptionPane.ERROR_MESSAGE);
            } else {
               // acadPesq = Integer.parseInt(acadPesquisada); // como a busca é por ID, então transformar esse valor em int passando o valor do parametro
               String acadPesq = academia.getNome();
               gerenciamento.atualizarAcademia(acadPesq, nome, endereco, telefone, mensalidade, atividadesOfertadas, qtd_personais);
                JOptionPane.showMessageDialog(null, "Academia "+academia.getNome()+" atualizada com sucesso!");
                setVisible(false);
                TelaMenuAcademia janela = new TelaMenuAcademia(academia);
                janela.setVisible(true);
            }

        }
        
    }//GEN-LAST:event_botao_atualizarActionPerformed

