        this.academia = academia;
        initComponents();
        ajustarTamanhoJanela();
        setLocationRelativeTo(null);
        configurarBotoesAposInit();
        
        campoNome_atua.setText(academia.getNome());
        campoEndereco_atua.setText(academia.getEndereco());
        campoTelefone_atua.setText(academia.getN_contato());
